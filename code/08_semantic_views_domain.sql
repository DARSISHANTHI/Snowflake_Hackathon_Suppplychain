        ),
        "Common root causes" AS (
            QUESTION 'What are the most common root causes of defects?'
            ONBOARDING_QUESTION FALSE
            SQL 'SELECT ROOT_CAUSE, COUNT(*) AS EVENT_COUNT, SUM(COST_OF_QUALITY) AS TOTAL_COST FROM AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_QUALITY_EVENT GROUP BY ROOT_CAUSE ORDER BY EVENT_COUNT DESC'
        )
    );

