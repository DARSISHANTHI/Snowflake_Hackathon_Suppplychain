    FACTS (
        DIM_SUPPLIER.RISK_SCORE AS RISK_SCORE,
        DIM_SUPPLIER.QUALITY_SCORE AS QUALITY_SCORE,
        DIM_SUPPLIER.DELIVERY_SCORE AS DELIVERY_SCORE,
