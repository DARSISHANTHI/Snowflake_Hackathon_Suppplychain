        FACT_PURCHASE_ORDER_LINE.QUANTITY_RECEIVED AS QUANTITY_RECEIVED,
        FACT_PURCHASE_ORDER_LINE.UNIT_PRICE AS UNIT_PRICE,
        FACT_PURCHASE_ORDER_LINE.LINE_VALUE AS LINE_VALUE,
        FACT_PURCHASE_ORDER_LINE.FREIGHT_COST AS FREIGHT_COST,
        FACT_PURCHASE_ORDER_LINE.LANDED_COST AS LANDED_COST
    )
    DIMENSIONS (
        DIM_SUPPLIER.SUPPLIER_ID AS SUPPLIER_ID,
        DIM_SUPPLIER.SUPPLIER_NAME AS SUPPLIER_NAME,
        DIM_SUPPLIER.COUNTRY AS COUNTRY,
        DIM_SUPPLIER.REGION AS REGION,
        DIM_SUPPLIER.TIER_LEVEL AS TIER_LEVEL,
        DIM_SUPPLIER.CATEGORY AS CATEGORY,
        DIM_SUPPLIER.FINANCIAL_RISK AS FINANCIAL_RISK,
        DIM_SUPPLIER.CERTIFICATION_STATUS AS CERTIFICATION_STATUS,
        DIM_SUPPLIER.IS_ACTIVE AS IS_ACTIVE,
        DIM_PART.PART_ID AS PART_ID,
        DIM_PART.PART_NAME AS PART_NAME,
        DIM_PART.PART_FAMILY AS PART_FAMILY,
        DIM_PART.ATA_CHAPTER AS ATA_CHAPTER,
        DIM_PART.CRITICALITY AS CRITICALITY,
        FACT_PURCHASE_ORDER.PO_ID AS PO_ID,
        FACT_PURCHASE_ORDER.SUPPLIER_ID AS SUPPLIER_ID,
        FACT_PURCHASE_ORDER.PLANT_ID AS PLANT_ID,
        FACT_PURCHASE_ORDER.STATUS AS STATUS,
        FACT_PURCHASE_ORDER.PRIORITY AS PRIORITY,
        FACT_PURCHASE_ORDER.ORDER_DATE AS ORDER_DATE,
        FACT_PURCHASE_ORDER.PROMISED_DATE AS PROMISED_DATE,
        FACT_PURCHASE_ORDER.RECEIVED_DATE AS RECEIVED_DATE,
        FACT_PURCHASE_ORDER_LINE.PO_LINE_ID AS PO_LINE_ID,
        FACT_PURCHASE_ORDER_LINE.PO_ID AS PO_ID,
        FACT_PURCHASE_ORDER_LINE.PART_ID AS PART_ID
    )
    COMMENT = 'Procurement and supplier analytics: purchase orders, supplier performance, OTD, spend, landed cost, risk scores.'
    AI_VERIFIED_QUERIES (
        "Top suppliers by spend" AS (
            QUESTION 'Who are the top 10 suppliers by total procurement spend?'
            ONBOARDING_QUESTION FALSE
            SQL 'SELECT s.SUPPLIER_NAME, SUM(po.TOTAL_VALUE) AS TOTAL_SPEND FROM AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_PURCHASE_ORDER po JOIN AEROSPACE_SUPPLY_CHAIN_AI.RAW.DIM_SUPPLIER s ON po.SUPPLIER_ID = s.SUPPLIER_ID GROUP BY s.SUPPLIER_NAME ORDER BY TOTAL_SPEND DESC LIMIT 10'
        ),
        "Suppliers below 90% OTD" AS (
            QUESTION 'Which suppliers have delivery score below 90%?'
            ONBOARDING_QUESTION FALSE
            SQL 'SELECT SUPPLIER_NAME, DELIVERY_SCORE, RISK_SCORE FROM AEROSPACE_SUPPLY_CHAIN_AI.RAW.DIM_SUPPLIER WHERE DELIVERY_SCORE < 90 AND IS_ACTIVE = TRUE ORDER BY DELIVERY_SCORE'
        ),
        "Procurement spend by quarter" AS (
            QUESTION 'What is our procurement spend by quarter this year?'
            ONBOARDING_QUESTION FALSE
            SQL 'SELECT QUARTER(ORDER_DATE) AS QTR, SUM(TOTAL_VALUE) AS SPEND FROM AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_PURCHASE_ORDER WHERE YEAR(ORDER_DATE) = 2026 GROUP BY QTR ORDER BY QTR'
        )
    );

