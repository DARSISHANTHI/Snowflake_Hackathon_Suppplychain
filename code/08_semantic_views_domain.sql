        DIM_PLANT.PLANT_ID AS PLANT_ID,
        DIM_PLANT.PLANT_NAME AS PLANT_NAME,
        DIM_PLANT.REGION AS REGION,
        DIM_WORK_CENTER.WORK_CENTER_ID AS WORK_CENTER_ID,
        DIM_WORK_CENTER.WORK_CENTER_NAME AS WORK_CENTER_NAME,
        DIM_WORK_CENTER.WORK_CENTER_TYPE AS WORK_CENTER_TYPE,
        FACT_WORK_ORDER.WO_ID AS WO_ID,
        FACT_WORK_ORDER.PART_ID AS PART_ID,
        FACT_WORK_ORDER.PLANT_ID AS PLANT_ID,
        FACT_WORK_ORDER.WORK_CENTER_ID AS WORK_CENTER_ID,
        FACT_WORK_ORDER.STATUS AS STATUS,
        FACT_WORK_ORDER.WO_TYPE AS WO_TYPE,
        FACT_WORK_ORDER.PROGRAM AS PROGRAM,
