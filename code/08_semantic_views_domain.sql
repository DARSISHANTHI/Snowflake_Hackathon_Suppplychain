        FACT_WORK_ORDER.PLANNED_END_DATE AS PLANNED_END_DATE,
        FACT_WORK_ORDER.ACTUAL_END_DATE AS ACTUAL_END_DATE
    )
    COMMENT = 'Manufacturing analytics: production yield, scrap rate, work order completion, capacity utilization by plant and work center.'
    AI_VERIFIED_QUERIES (
        "Yield by plant" AS (
            QUESTION 'What is the average production yield by plant?'
            ONBOARDING_QUESTION FALSE
            SQL 'SELECT pl.PLANT_NAME, ROUND(AVG(wo.YIELD_RATE), 2) AS AVG_YIELD FROM AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_WORK_ORDER wo JOIN AEROSPACE_SUPPLY_CHAIN_AI.RAW.DIM_PLANT pl ON wo.PLANT_ID = pl.PLANT_ID WHERE wo.STATUS = ''Completed'' GROUP BY pl.PLANT_NAME ORDER BY AVG_YIELD'
        ),
        "Scrap by work center type" AS (
            QUESTION 'What is the scrap rate by work center type?'
            ONBOARDING_QUESTION FALSE
            SQL 'SELECT wc.WORK_CENTER_TYPE, ROUND(SUM(wo.QUANTITY_SCRAPPED)*100.0/NULLIF(SUM(wo.QUANTITY_PLANNED),0), 2) AS SCRAP_RATE FROM AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_WORK_ORDER wo JOIN AEROSPACE_SUPPLY_CHAIN_AI.RAW.DIM_WORK_CENTER wc ON wo.WORK_CENTER_ID = wc.WORK_CENTER_ID GROUP BY wc.WORK_CENTER_TYPE ORDER BY SCRAP_RATE DESC'
        ),
        "Parts below 95% yield" AS (
            QUESTION 'Which parts have yield below 95%?'
            ONBOARDING_QUESTION FALSE
            SQL 'SELECT p.PART_NAME, ROUND(AVG(wo.YIELD_RATE), 2) AS AVG_YIELD FROM AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_WORK_ORDER wo JOIN AEROSPACE_SUPPLY_CHAIN_AI.RAW.DIM_PART p ON wo.PART_ID = p.PART_ID WHERE wo.STATUS = ''Completed'' GROUP BY p.PART_NAME HAVING AVG(wo.YIELD_RATE) < 95 ORDER BY AVG_YIELD'
        )
    );

