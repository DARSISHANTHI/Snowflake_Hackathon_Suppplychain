    )
    DIMENSIONS (
        DIM_PART.PART_ID AS PART_ID,
        DIM_PART.PART_NAME AS PART_NAME,
        DIM_PART.PART_FAMILY AS PART_FAMILY,
        DIM_PART.CRITICALITY AS CRITICALITY,
        DIM_PLANT.PLANT_ID AS PLANT_ID,
        DIM_PLANT.PLANT_NAME AS PLANT_NAME,
        DIM_PLANT.COUNTRY AS COUNTRY,
        DIM_PLANT.REGION AS REGION,
        DIM_WAREHOUSE.WAREHOUSE_ID AS WAREHOUSE_ID,
        DIM_WAREHOUSE.WAREHOUSE_NAME AS WAREHOUSE_NAME,
        DIM_WAREHOUSE.WAREHOUSE_TYPE AS WAREHOUSE_TYPE,
        FACT_INVENTORY.INVENTORY_ID AS INVENTORY_ID,
        FACT_INVENTORY.PART_ID AS PART_ID,
        FACT_INVENTORY.PLANT_ID AS PLANT_ID,
        FACT_INVENTORY.WAREHOUSE_ID AS WAREHOUSE_ID,
        FACT_INVENTORY.SNAPSHOT_DATE AS SNAPSHOT_DATE,
        FACT_INVENTORY_MOVEMENT.MOVEMENT_ID AS MOVEMENT_ID,
        FACT_INVENTORY_MOVEMENT.MOVEMENT_TYPE AS MOVEMENT_TYPE,
        FACT_INVENTORY_MOVEMENT.PART_ID AS PART_ID,
        FACT_INVENTORY_MOVEMENT.PLANT_ID AS PLANT_ID,
        FACT_INVENTORY_MOVEMENT.MOVEMENT_DATE AS MOVEMENT_DATE
    )
    COMMENT = 'Inventory management analytics: stock levels, days of inventory, movements, warehouse utilization, reorder alerts.'
    AI_VERIFIED_QUERIES (
        "Parts below reorder point" AS (
            QUESTION 'Which parts are below their reorder point?'
            ONBOARDING_QUESTION FALSE
            SQL 'SELECT p.PART_NAME, i.AVAILABLE_QTY, i.REORDER_POINT, i.SAFETY_STOCK FROM AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_INVENTORY i JOIN AEROSPACE_SUPPLY_CHAIN_AI.RAW.DIM_PART p ON i.PART_ID = p.PART_ID WHERE i.AVAILABLE_QTY < i.REORDER_POINT ORDER BY i.AVAILABLE_QTY'
        ),
        "Average DOI by plant" AS (
            QUESTION 'What is the average days of inventory by plant?'
            ONBOARDING_QUESTION FALSE
            SQL 'SELECT pl.PLANT_NAME, ROUND(AVG(i.DAYS_OF_INVENTORY), 1) AS AVG_DOI FROM AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_INVENTORY i JOIN AEROSPACE_SUPPLY_CHAIN_AI.RAW.DIM_PLANT pl ON i.PLANT_ID = pl.PLANT_ID GROUP BY pl.PLANT_NAME ORDER BY AVG_DOI'
        ),
        "Inventory value by warehouse type" AS (
            QUESTION 'What is total inventory value by warehouse type?'
            ONBOARDING_QUESTION FALSE
            SQL 'SELECT w.WAREHOUSE_TYPE, SUM(i.TOTAL_VALUE) AS TOTAL_VALUE FROM AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_INVENTORY i JOIN AEROSPACE_SUPPLY_CHAIN_AI.RAW.DIM_WAREHOUSE w ON i.WAREHOUSE_ID = w.WAREHOUSE_ID GROUP BY w.WAREHOUSE_TYPE ORDER BY TOTAL_VALUE DESC'
        )
    );

