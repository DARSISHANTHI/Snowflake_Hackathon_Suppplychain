-- ============================================================
-- SV_PROCUREMENT - Supplier and purchase order analytics
-- ============================================================
CREATE OR REPLACE SEMANTIC VIEW SV_PROCUREMENT
    TABLES (
        AEROSPACE_SUPPLY_CHAIN_AI.RAW.DIM_SUPPLIER UNIQUE (SUPPLIER_ID),
        AEROSPACE_SUPPLY_CHAIN_AI.RAW.DIM_PART UNIQUE (PART_ID),
        AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_PURCHASE_ORDER UNIQUE (PO_ID),
        AEROSPACE_SUPPLY_CHAIN_AI.RAW.FACT_PURCHASE_ORDER_LINE UNIQUE (PO_LINE_ID)
    )
    RELATIONSHIPS (
        PO_TO_SUPPLIER AS FACT_PURCHASE_ORDER(SUPPLIER_ID) REFERENCES DIM_SUPPLIER(SUPPLIER_ID),
        PO_LINE_TO_PART AS FACT_PURCHASE_ORDER_LINE(PART_ID) REFERENCES DIM_PART(PART_ID),
